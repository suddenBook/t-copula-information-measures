function report = verify_lfp_reproduction(candidate_path, reference_path)
    %VERIFY_LFP_REPRODUCTION Check that a reproduced LFP input equals the reference in every field Phase 1 reads.
    %
    % The MAT-file bytes and the descriptive metadata may differ, because each file records its input path and its creation time.
    % The comparison covers the fields Phase 1 reads (X by class, shape and exact values, fs, channel_ids, segment_boundaries) and the trial and filter provenance that defines the segment joins (trial_ids, the segment start and end tags, the filter range and order).
    % A missing file or field, or any difference, raises an error whose identifier names it (for example verify_lfp_reproduction:SignalMismatch).
    %
    % Inputs:
    %   candidate_path - reproduced .mat file, for example <TC_LFP_OUTPUT_ROOT>/monkey_L/baseline_correct_epoch.mat
    %   reference_path - reference .mat file, for example data/monkey_LFP/preprocessed/monkey_L/baseline_correct_epoch.mat
    % Outputs:
    %   report - struct with ok (true), the two paths, n_samples, n_channels, n_trials and filter_range

    arguments
        candidate_path (1, 1) string
        reference_path (1, 1) string
    end

    assert(isfile(candidate_path), 'verify_lfp_reproduction:MissingCandidate', ...
        'Candidate file does not exist: %s', candidate_path);
    assert(isfile(reference_path), 'verify_lfp_reproduction:MissingReference', ...
        'Reference file does not exist: %s', reference_path);

    fields = {'X', 'fs', 'channel_ids', 'segment_boundaries', 'trial_ids', ...
        'segment_start_tag', 'segment_end_tag', 'filter_params'};
    candidate = load(candidate_path, fields{:});
    reference = load(reference_path, fields{:});

    for k = 1:numel(fields)
        field = fields{k};
        assert(isfield(candidate, field) && isfield(reference, field), ...
            'verify_lfp_reproduction:MissingField', ...
            'Required field %s is absent from one input.', field);
    end

    assert(strcmp(class(candidate.X), class(reference.X)), ...
        'verify_lfp_reproduction:ClassMismatch', 'X classes differ.');
    assert(isequal(size(candidate.X), size(reference.X)), ...
        'verify_lfp_reproduction:ShapeMismatch', 'X shapes differ.');
    assert(isequal(candidate.X, reference.X), ...
        'verify_lfp_reproduction:SignalMismatch', ...
        'Prepared signal values are not bit-identical.');
    assert(isequal(candidate.fs, reference.fs), ...
        'verify_lfp_reproduction:SamplingRateMismatch', 'Sampling rates differ.');
    assert(isequal(candidate.channel_ids, reference.channel_ids), ...
        'verify_lfp_reproduction:ChannelMismatch', 'Retained channels differ.');
    assert(isequal(candidate.segment_boundaries, reference.segment_boundaries), ...
        'verify_lfp_reproduction:BoundaryMismatch', 'Trial boundaries differ.');
    assert(isequal(candidate.trial_ids, reference.trial_ids), ...
        'verify_lfp_reproduction:TrialMismatch', 'Retained trial IDs differ.');
    assert(strcmp(candidate.segment_start_tag, reference.segment_start_tag) && ...
        strcmp(candidate.segment_end_tag, reference.segment_end_tag), ...
        'verify_lfp_reproduction:TagMismatch', 'Segment tags differ.');
    assert(isequal(candidate.filter_params.filter_range, ...
        reference.filter_params.filter_range) && ...
        isequal(candidate.filter_params.filter_order, ...
        reference.filter_params.filter_order), ...
        'verify_lfp_reproduction:FilterMismatch', 'Filter parameters differ.');

    report = struct( ...
        'ok', true, ...
        'candidate_path', candidate_path, ...
        'reference_path', reference_path, ...
        'n_samples', size(candidate.X, 1), ...
        'n_channels', size(candidate.X, 2), ...
        'n_trials', numel(candidate.trial_ids), ...
        'filter_range', candidate.filter_params.filter_range);
end
