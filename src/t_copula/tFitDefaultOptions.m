function options = tFitDefaultOptions(overrides)
    %TFITDEFAULTOPTIONS Materialise and validate t-copula profile-fit options.
    %
    %   OPTIONS = TFITDEFAULTOPTIONS() returns every scientific and numerical default of the t-copula profile fit.
    %   Persist this struct in run identities instead of an empty override struct.
    %
    %   OPTIONS = TFITDEFAULTOPTIONS(OVERRIDES) replaces the named defaults with the nonempty values of the scalar struct OVERRIDES; an empty value keeps its default.
    %   Extra fields are kept, so callers such as tFitChannelSet can carry their own options in the same struct, and only the fitter-owned fields listed below are validated here.
    %
    %   The shape parameter is p = 1/nu on the linear domain [0, 3] by default (nu >= 1/3).
    %   p = 0 is the Gaussian copula on the lower bound and a valid estimate, so p_bounds(1) must be exactly 0, and the tolerances and steps on p below (tol_x, gaussian_snap_tolerance, curvature_step, profile_ambiguity_min_p_separation, boundary_p_tolerance) are in p units, not log units.
    %   The heavy end carries no exclusion: a p_hat within boundary_p_tolerance of p_bounds(2) is recorded as heavy_boundary and the fit stays reportable.
    %
    %   Fields:
    %     p_bounds                          [0 3]; p_bounds(1) == 0 exactly
    %     tol_x                             1e-6; fminbnd TolX, absolute in p
    %     gaussian_snap_tolerance           1e-5; a refined p at or below this snaps to 0 unless it beats the Gaussian node
    %     curvature_step                    0.005; curvature and neighbour step
    %     profile_grid_size                 41; odd integer >= 5
    %     profile_ll_tol_per_row            2e-6; comparison slack per row
    %     profile_ambiguity_ll_tol_per_row  3e-5; separated near-tie slack per row
    %     profile_ambiguity_min_p_separation 0.01; distinct-peak separation in p
    %     boundary_p_tolerance              0.05; heavy-end flag distance from p_hi
    %     store_profile                     true; retain the profile vectors
    %     min_rows                          10; fewest complete rows a fit accepts
    %     r_min_eig                         1e-10; smallest admissible eigenvalue of R
    %     r_sym_tol                         1e-10; Frobenius tolerance on R - R'
    %     r_diag_tol                        1e-8; tolerance on |diag(R) - 1|
    %     max_projection_shift_rms          0.02; RMS off-diagonal repair shift above which the repair is gross

    arguments
        overrides (1, 1) struct = struct()
    end

    options = struct( ...
        "p_bounds", [0, 3], ...
        "tol_x", 1e-6, ...
        "gaussian_snap_tolerance", 1e-5, ...
        "curvature_step", 0.005, ...
        "profile_grid_size", 41, ...
        "profile_ll_tol_per_row", 2e-6, ...
        "profile_ambiguity_ll_tol_per_row", 3e-5, ...
        "profile_ambiguity_min_p_separation", 0.01, ...
        "boundary_p_tolerance", 0.05, ...
        "store_profile", true, ...
        "min_rows", 10, ...
        "r_min_eig", 1e-10, ...
        "r_sym_tol", 1e-10, ...
        "r_diag_tol", 1e-8, ...
        "max_projection_shift_rms", 0.02);

    overrideNames = fieldnames(overrides);
    for index = 1:numel(overrideNames)
        name = overrideNames{index};
        if ~isempty(overrides.(name)) || ~isfield(options, name)
            options.(name) = overrides.(name);
        end
    end

    validateattributes(options.p_bounds, {'numeric'}, ...
        {'vector', 'numel', 2, 'real', 'finite', 'nonnegative', 'increasing'}, ...
        mfilename, 'p_bounds');
    if options.p_bounds(1) ~= 0
        error("tFitDefaultOptions:GaussianBoundNotZero", ...
            ['p_bounds(1) must be exactly 0: p = 0 is the Gaussian copula and ' ...
            'the lower bound is a valid estimate, not an excluded artefact ' ...
            '(got %.6g).'], options.p_bounds(1));
    end
    % The heavy end is a working-domain choice, not a mathematical limit: the t copula is defined for every nu > 0, so p_bounds(2) has no upper limit, and the study's [0, 3] is one admissible setting among many.
    % Its lower limit comes from the tolerance ordering below, which needs p_bounds(2) / (profile_grid_size - 1) > profile_ambiguity_min_p_separation, that is p_bounds(2) > 0.4 at the defaults.
    validateattributes(options.tol_x, {'numeric'}, ...
        {'scalar', 'real', 'finite', 'positive'}, mfilename, 'tol_x');
    validateattributes(options.gaussian_snap_tolerance, {'numeric'}, ...
        {'scalar', 'real', 'finite', 'positive'}, ...
        mfilename, 'gaussian_snap_tolerance');
    validateattributes(options.curvature_step, {'numeric'}, ...
        {'scalar', 'real', 'finite', 'positive'}, mfilename, 'curvature_step');
    validateattributes(options.profile_grid_size, {'numeric'}, ...
        {'scalar', 'integer', '>=', 5}, mfilename, 'profile_grid_size');
    if mod(options.profile_grid_size, 2) ~= 1
        error("tFitDefaultOptions:EvenProfileGrid", ...
            "profile_grid_size must be odd (got %d).", ...
            options.profile_grid_size);
    end
    validateattributes(options.profile_ll_tol_per_row, {'numeric'}, ...
        {'scalar', 'real', 'finite', 'nonnegative'}, ...
        mfilename, 'profile_ll_tol_per_row');
    validateattributes(options.profile_ambiguity_ll_tol_per_row, {'numeric'}, ...
        {'scalar', 'real', 'finite', 'nonnegative'}, ...
        mfilename, 'profile_ambiguity_ll_tol_per_row');
    validateattributes(options.profile_ambiguity_min_p_separation, ...
        {'numeric'}, {'scalar', 'real', 'finite', 'positive'}, ...
        mfilename, 'profile_ambiguity_min_p_separation');
    validateattributes(options.boundary_p_tolerance, {'numeric'}, ...
        {'scalar', 'real', 'finite', 'nonnegative'}, ...
        mfilename, 'boundary_p_tolerance');
    validateattributes(options.store_profile, {'logical', 'numeric'}, ...
        {'scalar', 'real', 'finite'}, mfilename, 'store_profile');
    if ~ismember(double(options.store_profile), [0, 1])
        error("tFitDefaultOptions:InvalidStoreProfile", ...
            "store_profile must be a scalar logical value.");
    end
    options.store_profile = logical(options.store_profile);
    validateattributes(options.min_rows, {'numeric'}, ...
        {'scalar', 'integer', '>=', 2}, mfilename, 'min_rows');
    validateattributes(options.r_min_eig, {'numeric'}, ...
        {'scalar', 'real', 'finite', 'nonnegative'}, ...
        mfilename, 'r_min_eig');
    validateattributes(options.r_sym_tol, {'numeric'}, ...
        {'scalar', 'real', 'finite', 'nonnegative'}, ...
        mfilename, 'r_sym_tol');
    validateattributes(options.r_diag_tol, {'numeric'}, ...
        {'scalar', 'real', 'finite', 'nonnegative'}, ...
        mfilename, 'r_diag_tol');
    validateattributes(options.max_projection_shift_rms, {'numeric'}, ...
        {'scalar', 'real', 'finite', 'nonnegative'}, ...
        mfilename, 'max_projection_shift_rms');

    % The four p-scale tolerances must stay ordered for the estimator to mean what it says: the optimiser resolves p finer than the Gaussian snap, the snap is tighter than the separation that makes two basins distinct, and two distinct basins are resolvable inside one grid step.
    gridStep = options.p_bounds(2) / (options.profile_grid_size - 1);
    if ~(options.tol_x < options.gaussian_snap_tolerance ...
            && options.gaussian_snap_tolerance ...
            < options.profile_ambiguity_min_p_separation ...
            && options.profile_ambiguity_min_p_separation < gridStep)
        error("tFitDefaultOptions:ToleranceOrdering", ...
            ['The p-scale tolerances must satisfy tol_x < ' ...
            'gaussian_snap_tolerance < profile_ambiguity_min_p_separation < ' ...
            'p_bounds(2)/(profile_grid_size-1); got %.6g, %.6g, %.6g, %.6g.'], ...
            options.tol_x, options.gaussian_snap_tolerance, ...
            options.profile_ambiguity_min_p_separation, gridStep);
    end
end
