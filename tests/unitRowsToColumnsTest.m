classdef unitRowsToColumnsTest < matlab.unittest.TestCase
    %UNITROWSTOCOLUMNSTEST The column layout of the unit rows is lossless.
    %
    % Every MAT file that holds unit rows stores them column-wise, because a -v7.3 struct array costs about 400 bytes of HDF5 header per field per element and a recording holds about 180,000 unit rows.
    % The phases write through unitRowsToColumns and read back through unitColumnsToRows or by indexing the columns, so if the pair were not an exact inverse every number downstream would be silently reattached to the wrong unit.
    %
    % The tests pin the exact round trip over a mixed set of rows including an error path (NaN estimates, a different reason, a failed status), the declared layout of every column, index selection, the empty case, and the label decoding that unitRowsToTable and the Python readers both rely on.
    %
    % The suite uses synthetic rows only and reads no recordings.

    methods (TestClassSetup)
        function addSourceTree(testCase)
            sourceTree = fullfile( ...
                fileparts(fileparts(mfilename('fullpath'))), 'src');
            assert(isfolder(sourceTree), ...
                'unitRowsToColumnsTest:SourceTreeNotFound', ...
                'expected this file under <repo>/tests/; got %s', ...
                mfilename('fullpath'));
            testCase.applyFixture(matlab.unittest.fixtures.PathFixture( ...
                sourceTree, IncludingSubfolders=true));
        end
    end

    methods (Test)
        function roundTripIsExact(testCase)
            rows = localRows();

            back = unitColumnsToRows(unitRowsToColumns(rows));

            testCase.verifyEqual(fieldnames(back), fieldnames(rows), ...
                'the field order of the row must survive the trip.');
            testCase.verifyTrue(isequaln(back, rows), ...
                ['every unit row must come back with the same values, NaN ' ...
                'included; isequal treats a restored double 0/1 and the ' ...
                'original logical as equal.']);
        end

        function layoutIsTheDeclaredOne(testCase)
            rows = localRows();

            columns = unitRowsToColumns(rows);

            n = numel(rows);
            testCase.verifyEqual(columns.dataset_key, rows(1).dataset_key, ...
                'dataset_key is stored once, as a char.');
            testCase.verifySize(columns.p_hat, [n, 1]);
            testCase.verifyClass(columns.p_hat, 'double');
            testCase.verifySize(columns.channels, [n, 20]);
            testCase.verifySize(columns.profile_p_grid, [n, 41]);
            testCase.verifySize(columns.profile_loglik_grid, [n, 41]);
            testCase.verifyClass(columns.status, 'int8');
            testCase.verifySize(columns.status, [n, 1]);
            testCase.verifyClass(columns.reason, 'int8');
            testCase.verifyClass(columns.numerical_ok, 'double', ...
                'a logical column is stored as double 0/1.');
            testCase.verifyEqual(columns.numerical_ok, ...
                double([rows.numerical_ok]).');
            testCase.verifyEqual(columns.channels(2, :), rows(2).channels);
        end

        function labelsAreSortedAndDecodeBack(testCase)
            rows = localRows();

            columns = unitRowsToColumns(rows);

            testCase.verifyEqual(columns.status_labels, ...
                sort(unique({rows.status})), ...
                'the label list is the sorted distinct values.');
            testCase.verifyEqual(columns.reason_labels, ...
                sort(unique({rows.reason})));
            decoded = columns.status_labels(double(columns.status));
            testCase.verifyEqual(reshape(decoded, 1, []), {rows.status}, ...
                'the codes must index their own label list.');
            % The empty reason of a successful fit is a label like any other and sorts first, so it must survive rather than become code 0.
            testCase.verifyEqual(columns.reason_labels{1}, '');
        end

        function mixedDatasetKeyIsRefused(testCase)
            rows = localRows();
            rows(2).dataset_key = 'another/recording';

            testCase.verifyError(@() unitRowsToColumns(rows), ...
                'unitRowsToColumns:MixedDatasetKey');
        end

        function raggedOrTransposedFieldIsRefused(testCase)
            rows = localRows();
            rows(3).channels = nan(1, 19);

            testCase.verifyError(@() unitRowsToColumns(rows), ...
                'unitRowsToColumns:RaggedField');

            % A column vector stacks just as happily and would come back transposed, so the shape is checked and not only the count.
            transposed = localRows();
            transposed(1).profile_p_grid = transposed(1).profile_p_grid.';
            testCase.verifyError(@() unitRowsToColumns(transposed), ...
                'unitRowsToColumns:UnsupportedShape');
        end

        function indexSelectsUnitsInTheOrderGiven(testCase)
            rows = localRows();
            columns = unitRowsToColumns(rows);

            picked = unitColumnsToRows(columns, [3, 1]);

            testCase.verifyTrue(isequaln(picked, rows([3, 1])));
            testCase.verifyError(@() unitColumnsToRows(columns, numel(rows) + 1), ...
                'unitColumnsToRows:IndexOutOfRange');
            % idx is an index list, so an all-true logical mask, which passes the argument validators, must meet the explicit refusal.
            testCase.verifyError(@() unitColumnsToRows(columns, true(1, numel(rows))), ...
                'unitColumnsToRows:LogicalIndex');
        end

        function zeroUnitsRoundTrip(testCase)
            rows = localRows();
            empty_rows = rows([]);

            columns = unitRowsToColumns(empty_rows);
            back = unitColumnsToRows(columns);

            testCase.verifyEqual(numel(back), 0, ...
                'a dimension with no channel set must stay empty.');
            testCase.verifyEqual(fieldnames(back), fieldnames(rows), ...
                'the field set survives even with no unit to carry it.');
            testCase.verifyEqual(numel(unitColumnsToRows( ...
                unitRowsToColumns(rows), [])), 0, ...
                'an empty index selects no unit.');
        end

        function tableIsTheSameFromEitherLayout(testCase)
            rows = localRows();

            from_rows = unitRowsToTable(rows);
            from_columns = unitRowsToTable(unitRowsToColumns(rows));

            testCase.verifyEqual(from_columns.Properties.VariableNames, ...
                from_rows.Properties.VariableNames, ...
                'both layouts must produce the same CSV columns in the same order.');
            for name = from_rows.Properties.VariableNames
                testCase.verifyTrue(isequaln(from_columns.(name{1}), ...
                    from_rows.(name{1})), ...
                    sprintf('column "%s" differs between the two layouts.', name{1}));
            end
        end
    end
end


function rows = localRows()
    % Three unit rows with one field set: two fitted units of different status (a pair and a five-channel set) and a failed three-channel set with NaN estimates and its own reason, the mixture a phase's output carries.
    rows = [localRow(2, 1, [4, 9], 0.12, 'ok', ''), ...
        localRow(5, 1, [1, 2, 3, 7, 8], 2.98, 'heavy_boundary', ''), ...
        localRow(3, 4, [2, 5, 6], NaN, 'numerical_failure', 'too_few_rows')];
end


function row = localRow(d, unit_index, channels, p_hat, status, reason)
    % One row with the field set of tFitUnit, in its order.
    grid = linspace(0, 3, 41);
    ok = isfinite(p_hat);
    row = struct( ...
        'dataset_key', 'monkey_ECoG/EC1', ...
        'd', d, ...
        'unit_index', unit_index, ...
        'channels', [channels, nan(1, 20 - numel(channels))], ...
        'n', 1000, ...
        'p_hat', p_hat, ...
        'nu_hat', 1 / p_hat, ...
        'loglik_t', 12.5 * d, ...
        'loglik_gaussian', 12.0 * d, ...
        'aic_diff', d, ...
        'rho', 0.4, ...
        'tau', 0.26, ...
        'max_abs_rho', 0.4, ...
        'mean_abs_rho', 0.3, ...
        'logdet_R', -0.2 * d, ...
        'sum_logdet_minors', -0.1 * d, ...
        'cond_R', 3.1, ...
        'min_eig_R', 0.6, ...
        'repair_applied', d >= 3, ...
        'repair_shift_rms', 0.001 * d, ...
        'repair_gross', false, ...
        'degenerate_pair', false, ...
        'gaussian_snapped', p_hat == 0, ...
        'ambiguous_profile', false, ...
        'heavy_boundary', strcmp(status, 'heavy_boundary'), ...
        'numerical_ok', ok, ...
        'status', status, ...
        'reason', reason, ...
        'optimizer_exitflag', double(ok), ...
        'profile_p_grid', grid, ...
        'profile_loglik_grid', ok * grid - grid .^ 2, ...
        'fit_seconds', 0.01 * d);
end
